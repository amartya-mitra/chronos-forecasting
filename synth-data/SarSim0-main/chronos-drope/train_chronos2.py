"""
Chronos-2 Fine-Tuning with SarSim0 Synthetic Data.

This script fine-tunes Chronos-2 on synthetic time series generated by SarSim0.
Supports both full fine-tuning and LoRA fine-tuning.
Uses on-the-fly data generation with multiple workers for infinite data variety.

Usage:
    python train_chronos2.py --num_steps 1000 --batch_size 32 --finetune_mode lora
    python train_chronos2.py --num_steps 5000 --batch_size 64 --finetune_mode full
"""

